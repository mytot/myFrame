#!/usr/bin/env python3
"""
gen_store_key_header.py — embed the store root public key in the firmware.

The device pins one Ed25519 public key: the store root. That key signs the
catalog; catalog entries carry per-app publisher keys, and sideloaded packages
must be signed by the root itself. Only the PUBLIC half is ever compiled in.

    python3 tools/gen_store_key_header.py --key keys/dev/store_root.pub \
        --out build/frame_gen/frame_store_root_gen.h

`--key` accepts a 32-byte raw public key or the 64-byte seed||pub file that
frame_crypto.py writes. If the file is missing the header marks the key as
absent, which makes the store refuse network installs until a key is entered
in Settings → Developer — a safe default rather than a build break.
"""
import argparse
import os
import sys


def read_pub(path: str):
    with open(path, "rb") as f:
        data = f.read()
    if len(data) == 64:
        data = data[32:]
    if len(data) != 32:
        raise SystemExit(f"{path}: expected 32-byte public key (or 64-byte key file), got {len(data)} bytes")
    return data


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--key", required=True, help="path to the *.pub file (or '-' for none)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--source", default="", help="provenance note written into the header")
    args = ap.parse_args()

    if args.key == "-" or not os.path.exists(args.key):
        body = "#define FRAME_STORE_ROOT_KEY_NONE 1\n"
        note = "no key file supplied; network installs are disabled until a key is set at runtime"
    else:
        pub = read_pub(args.key)
        rows = []
        for i in range(0, 32, 8):
            rows.append("    " + ", ".join(f"0x{b:02x}u" for b in pub[i:i + 8]) + ",")
        body = ("#define FRAME_STORE_ROOT_KEY_NONE 0\n"
                "static const uint8_t FRAME_STORE_ROOT_KEY[32] = {\n" + "\n".join(rows) + "\n};\n")
        note = args.source or args.key

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("/* Generated by tools/gen_store_key_header.py — do not edit. */\n")
        f.write(f"/* Store root public key source: {note} */\n")
        f.write("#pragma once\n\n#include <stdint.h>\n\n")
        f.write(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
